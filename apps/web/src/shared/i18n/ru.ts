function plural(n: number, one: string, few: string, many: string): string {
  const absolute = Math.abs(n);
  const lastTwo = absolute % 100;
  if (lastTwo >= 11 && lastTwo <= 14) return many;
  const last = absolute % 10;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

/** «1 элемент», «1 204 элемента». */
const items = (n: number) => `${count(n)} ${plural(n, "элемент", "элемента", "элементов")}`;

/** «1 другой элемент», «3 других элемента». */
const others = (n: number) =>
  `${count(n)} ${plural(n, "другой элемент", "других элемента", "других элементов")}`;

/** «Spotify и Discord»; больше трёх названий: «A, B, C и ещё 2». */
function appList(apps: readonly string[]): string {
  if (apps.length > 3) {
    return `${apps.slice(0, 3).join(", ")} и ещё ${count(apps.length - 3)}`;
  }
  return new Intl.ListFormat("ru", { type: "conjunction" }).format(apps);
}

